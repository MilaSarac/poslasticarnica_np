package rs.ac.bg.fon.ai.transfer.util;

/**
 * Enumeracija koja predstavlja moguce rezultate izvrsavanja operacije.
 * 
 * Moze da oznaci da li je odredjena operacija uspesno izvrsena
 * ili je prilikom njenog izvrsavanja doslo do greske.
 * 
 * @author Mila
 */
public enum RezultatOp {

    /**
     * Oznacava uspesno izvrsenu operaciju.
     */
    Uspeh,

    /**
     * Oznacava da je prilikom izvrsavanja operacije doslo do greske.
     */
    Greska
}
    private void btnSacuvajActionPerformed(java.awt.event.ActionEvent evt) {                                           
        try {
            String urlInput = txtUrl.getText().trim();
            String username = txtUser.getText().trim();
            String password = new String(txtPass.getPassword());

            if (urlInput.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Unesite URL!");
                return;
            }

            Path cfg = Paths.get("konfiguracija.properties");
            Properties prop = new Properties();

            if (Files.exists(cfg)) {
                try (InputStream in = Files.newInputStream(cfg)) {
                    prop.load(in);
                }
            }

            prop.setProperty("url", urlInput);
            prop.setProperty("username", username);
            prop.setProperty("password", password);

            try (OutputStream out = Files.newOutputStream(cfg,
                    StandardOpenOption.CREATE,
                    StandardOpenOption.TRUNCATE_EXISTING,
                    StandardOpenOption.WRITE)) {
                prop.store(out, "Konfiguracija baze");
            }

            JOptionPane.showMessageDialog(this, "Konfiguracija uspešno sačuvana.");
            this.dispose();

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Greška pri čuvanju konfiguracije!", "GREŠKA", JOptionPane.ERROR_MESSAGE);
        }
    }                                                


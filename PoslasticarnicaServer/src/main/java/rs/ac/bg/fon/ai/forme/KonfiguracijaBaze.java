    private void popuniPolja() {
        try {
            Properties properties = new Properties();
            Path cfg = Paths.get("konfiguracija.properties");

            if (Files.exists(cfg)) {
                try (InputStream in = Files.newInputStream(cfg)) {
                    properties.load(in);
                }
            }

            //izvlacenje vrednosti
            String url = properties.getProperty("url", "jdbc:mysql://localhost:3308/poslasticarnica_ps");
            String username = properties.getProperty("username", "");
            String password = properties.getProperty("password", "");

            //popunjavanje polja na formi
            txtUrl.setText(url);
            txtUser.setText(username);
            txtPass.setText(password);

        } catch (Exception ex) {
            Logger.getLogger(KonfiguracijaBaze.class.getName()).log(Level.WARNING, "Ne mogu da učitam konfiguraciju", ex);
            txtUrl.setText("jdbc:mysql://localhost:3308/poslasticarnica_ps");
            txtUser.setText("");
            txtPass.setText("");
        }
        
    }
